CREATE TABLE IF NOT EXISTS automations (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  tenant_id CHAR(36) NULL,
  name VARCHAR(100) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  trigger_device_id CHAR(36) NOT NULL,
  trigger_metric VARCHAR(32) NOT NULL,
  operator ENUM('>','>=','<','<=','==','!=') NOT NULL,
  threshold_value DOUBLE NOT NULL,
  action_device_id CHAR(36) NOT NULL,
  action_type ENUM('switch_channel','scene') NOT NULL DEFAULT 'switch_channel',
  action_channel_index INT UNSIGNED NULL,
  action_state BOOLEAN NULL,
  action_scene_id CHAR(36) NULL,
  cooldown_seconds INT UNSIGNED NOT NULL DEFAULT 60,
  last_triggered_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY(user_id) REFERENCES users(id),
  FOREIGN KEY(trigger_device_id) REFERENCES devices(id),
  FOREIGN KEY(action_device_id) REFERENCES devices(id),
  INDEX(trigger_device_id, enabled),
  INDEX(user_id, enabled),
  INDEX(tenant_id, enabled)
) ENGINE=InnoDB;
